import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { catalogMetadataSchema, exampleMetadataSchema, exampleSnapshotSchema } from '../src/lib/example-schema';

async function readOptionalSource(path: string) {
  try {
    return (await readFile(path, 'utf8')).trimEnd();
  } catch (error: unknown) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return undefined;
    throw error;
  }
}

/** Read canonical problem folders and validate the complete catalog before emitting anything. */
export async function readExampleCatalog(sourceDirectory: string) {
  const catalog = catalogMetadataSchema.parse(JSON.parse(await readFile(join(sourceDirectory, 'catalog.json'), 'utf8')));
  const folders = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const examples = await Promise.all(folders.map(async (slug) => {
    const directory = join(sourceDirectory, slug);
    try {
      const [metadata, birdie, python, providedTypes] = await Promise.all([
        readFile(join(directory, 'problem.json'), 'utf8'),
        readOptionalSource(join(directory, 'solution.bd')),
        readOptionalSource(join(directory, 'solution.py')),
        readOptionalSource(join(directory, 'provided-types.bd')),
      ]);

      if ((birdie === undefined) !== (python === undefined)) {
        throw new Error('solution.bd and solution.py must either both exist or both be absent.');
      }

      return {
        ...exampleMetadataSchema.parse(JSON.parse(metadata)),
        slug,
        ...(birdie === undefined || python === undefined ? {} : { birdie, python }),
        ...(providedTypes === undefined ? {} : { providedTypes }),
      };
    } catch (error: unknown) {
      throw new Error(`Invalid example ${slug}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
    }
  }));

  return exampleSnapshotSchema.parse({
    generatedFrom: 'birdie/examples/leetcode; run bun run sync:examples; do not edit this file',
    catalog,
    examples,
  });
}
