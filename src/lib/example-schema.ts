import { z } from 'astro/zod';

const text = z.string().trim().min(1);
const positiveInteger = z.number().int().positive();
const neetcodeCategory = z.enum([
  'Arrays & Hashing',
  'Two Pointers',
  'Sliding Window',
  'Stack',
  'Binary Search',
  'Linked List',
  'Trees',
  'Tries',
  'Heap / Priority Queue',
  'Backtracking',
  'Graphs',
  'Advanced Graphs',
  '1-D Dynamic Programming',
  '2-D Dynamic Programming',
  'Greedy',
  'Intervals',
  'Math & Geometry',
  'Bit Manipulation',
]);

export const catalogMetadataSchema = z.object({
  neetcode150: z.object({
    url: z.url(),
    orderSource: z.url(),
  }).strict(),
}).strict();

export const exampleMetadataSchema = z.object({
  title: text,
  difficulty: z.enum(['Easy', 'Medium', 'Hard']),
  leetcode: z.object({
    id: positiveInteger,
    url: z.url().regex(/^https:\/\/leetcode\.com\/problems\/[a-z0-9-]+\/description\/$/),
  }).strict(),
  neetcode150: z.object({
    position: positiveInteger.max(150),
    category: neetcodeCategory,
  }).strict().optional(),
  blind75: z.boolean(),
  featuredOrder: positiveInteger.optional(),
  concept: text.optional(),
  description: text.optional(),
  note: text.optional(),
  notes: z.array(text).optional(),
}).strict();

const pendingExampleSchema = exampleMetadataSchema.extend({
  slug: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  providedTypes: text.optional(),
});

const adapterSchema = z.enum(['', 'json', 'tree', 'node']);
const methodCallSchema = z.object({
  method: text,
  args: z.array(text),
}).strict();
const exampleCaseSchema = z.object({
  name: text,
  args: z.array(text),
  calls: z.array(methodCallSchema).optional(),
  expected: text,
}).strict();

const exampleFixtureSchema = z.object({
  entry: text,
  check: z.enum(['', 'exact', 'unordered', 'unordered-groups', 'codec-round-trip']).optional(),
  argAdapters: z.array(adapterSchema).optional(),
  resultAdapter: adapterSchema.optional(),
  cases: z.array(exampleCaseSchema).min(1),
}).strict();

export type ExampleFixture = z.infer<typeof exampleFixtureSchema>;

const sourceFixtureSchema = exampleFixtureSchema.extend({
  cases: z.array(exampleCaseSchema.extend({
    args: z.array(z.unknown()),
    calls: z.array(methodCallSchema.extend({ args: z.array(z.unknown()) })).optional(),
    expected: z.unknown(),
  })).min(1),
});

export function parseExampleFixture(source: string): ExampleFixture {
  // Keep values as JSON text in the snapshot so large Birdie integers survive JavaScript's number parsing.
  const decoded: unknown = JSON.parse(source, (_key: string, value: unknown, context?: { source?: string }) => {
    if (typeof value !== 'number' || Number.isSafeInteger(value)) return value;
    if (!context?.source || !('rawJSON' in JSON) || typeof JSON.rawJSON !== 'function') {
      throw new Error('The JavaScript runtime cannot preserve this fixture number.');
    }
    return JSON.rawJSON(context.source);
  });
  const fixture = sourceFixtureSchema.parse(decoded);
  return exampleFixtureSchema.parse({
    ...fixture,
    cases: fixture.cases.map(({ name, args, calls, expected }) => ({
      name,
      args: args.map((arg) => JSON.stringify(arg)),
      ...(calls === undefined ? {} : {
        calls: calls.map(({ method, args }) => ({ method, args: args.map((arg) => JSON.stringify(arg)) })),
      }),
      expected: JSON.stringify(expected),
    })),
  });
}

const translatedExampleSchema = pendingExampleSchema.extend({
  birdie: text,
  python: text,
  fixture: exampleFixtureSchema.optional(),
});

export const exampleSchema = z.union([translatedExampleSchema, pendingExampleSchema]);

export const exampleSnapshotSchema = z.object({
  generatedFrom: z.literal('birdie/examples/leetcode; run bun run sync:examples; do not edit this file'),
  catalog: catalogMetadataSchema,
  examples: z.array(exampleSchema),
}).strict().superRefine((snapshot, context) => {
  const seen = new Set<string>();
  snapshot.examples.forEach((example, index) => {
    const identities = [
      ['slug', example.slug],
      ['leetcode.id', example.leetcode.id],
      ['neetcode150.position', example.neetcode150?.position],
      ['featuredOrder', example.featuredOrder],
    ] as const;

    for (const [key, value] of identities) {
      if (value === undefined) continue;
      const identity = `${key}:${value}`;
      if (seen.has(identity)) {
        context.addIssue({
          code: 'custom',
          path: ['examples', index, ...key.split('.')],
          message: `Duplicate ${key}: ${value}`,
        });
      }
      seen.add(identity);
    }

    if (example.featuredOrder !== undefined) {
      if (!('birdie' in example)) {
        context.addIssue({ code: 'custom', path: ['examples', index, 'featuredOrder'], message: 'A featured problem must have both solutions.' });
      }
      for (const field of ['concept', 'description', 'note'] as const) {
        if (example[field] === undefined) {
          context.addIssue({ code: 'custom', path: ['examples', index, field], message: `A featured problem requires ${field}.` });
        }
      }
    }
  });
});
